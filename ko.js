function tr(value) {
  if(value==null) return value;
  const s=String(value);
  if(Object.prototype.hasOwnProperty.call(KO_UI,s)) return KO_UI[s];
  if(Object.prototype.hasOwnProperty.call(KO_FLAVOR,s)) return KO_FLAVOR[s];
  if(Object.prototype.hasOwnProperty.call(KO_NAMES,s)) return KO_NAMES[s];
  if(Object.prototype.hasOwnProperty.call(KO_NAMES,s.trim())) return KO_NAMES[s.trim()];
  if(Object.prototype.hasOwnProperty.call(EXTRA_EFFECTS,s)) return EXTRA_EFFECTS[s];
  if(Object.prototype.hasOwnProperty.call(EXTRA_EFFECTS_MORE,s)) return EXTRA_EFFECTS_MORE[s];
  if(Object.prototype.hasOwnProperty.call(EXTRA_EFFECTS_FINAL,s)) return EXTRA_EFFECTS_FINAL[s];
  if(Object.prototype.hasOwnProperty.call(EXTRA_EFFECTS_LAST,s)) return EXTRA_EFFECTS_LAST[s];
  const effect=translateEffect(s);
  if(effect!==null) return containsUntranslatedEnglish(effect) ? s : effect;
  // Many Atlas nodes contain several independent stat lines. Translate each line
  // independently while preserving line breaks and leaving unknown lines untouched.
  if(s.includes('\n')) return s.split('\n').map(line => { const t=translateEffect(line); return t!==null && !containsUntranslatedEnglish(t) ? t : line; }).join('\n');
  // Titles get a conservative term translation. Unknown effect sentences remain English,
  // avoiding the previous broken word-by-word output.
  if(/^[A-Z][A-Za-z' -]+$/.test(s) && !/[.!?]/.test(s)) { const t=phrase(s); return containsUntranslatedEnglish(t) ? s : t; }
  return s;
}

