function particle(word, kind='subject') {
  const chars=String(word).match(/[가-힣]/g);
  if (!chars) return kind==='topic'?'은':'가';
  const jong=(chars[chars.length-1].charCodeAt(0)-0xAC00)%28!==0;
  if(kind==='subject') return jong?'이':'가';
  if(kind==='topic') return jong?'은':'는';
  if(kind==='object') return jong?'을':'를';
  return jong?'과':'와';
}
